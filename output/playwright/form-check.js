async (page) => {
  const checks = [];
  const verify = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  await page.getByRole('button', { name: 'Describir el problema' }).click();
  verify(await page.getByText('Elegí el espacio que necesitás proteger.').isVisible(), 'Required space error');
  verify(await page.locator('[name=espacio]').first().evaluate(el => el === document.activeElement), 'First error focused');
  await page.getByText('Mi hogar', { exact: true }).click();
  await page.getByRole('button', { name: 'Describir el problema' }).click();
  await page.getByRole('button', { name: 'Completar mis datos' }).click();
  verify(await page.getByText('Elegí una plaga o seleccioná que necesitás identificarla.').isVisible(), 'Required pest error');
  await page.getByRole('combobox').selectOption('cucarachas');
  await page.getByRole('textbox', { name: 'Barrio o localidad' }).fill('Caballito');
  await page.getByRole('spinbutton').fill('0');
  await page.getByRole('button', { name: 'Completar mis datos' }).click();
  verify(await page.locator('[data-error-for=superficie]').isVisible(), 'Invalid surface rejected');
  await page.getByRole('spinbutton').fill('80');
  await page.getByRole('textbox', { name: '¿Algo más que debamos saber?' }).fill('Consulta de prueba, sin envío.');
  await page.getByRole('button', { name: 'Completar mis datos' }).click();
  await page.getByRole('button', { name: 'Revisar mi consulta' }).click();
  verify(await page.getByText('Ingresá tu nombre, con al menos 2 caracteres.').isVisible(), 'Required name error');
  await page.getByRole('textbox', { name: 'Tu nombre' }).fill('Prueba de diseño');
  await page.getByRole('checkbox', { name: 'Hay chicos o mascotas' }).check();
  await page.getByRole('button', { name: 'Revisar mi consulta' }).click();
  verify(await page.getByRole('heading', { name: 'Tu consulta está preparada.' }).isVisible(), 'Result shown');
  verify((await page.locator('[data-quote-summary]').innerText()).includes('Caballito'), 'Summary contains location');
  verify(await page.locator('[data-quote-send]').isHidden(), 'No fake WhatsApp destination');
  verify(await page.locator('[data-form-status]').isVisible(), 'Status remains accessible');
  await page.getByRole('button', { name: 'Editar datos' }).click();
  verify((await page.getByRole('textbox', { name: 'Tu nombre' }).inputValue()) === 'Prueba de diseño', 'Editing preserves values');
  await page.getByRole('button', { name: 'Revisar mi consulta' }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Descargar consulta' }).click();
  const download = await downloadPromise;
  await download.saveAs('output/playwright/solicitud-prueba.txt');
  verify(download.suggestedFilename() === 'solicitud-traza.txt', 'Download completed');
  verify((await page.locator('[data-form-status]').innerText()).includes('todavía no fue enviada'), 'Honest download confirmation');
  await page.screenshot({ path: 'output/playwright/quote-result.png' });
  return { checks, summary: await page.locator('[data-quote-summary]').innerText() };
}
